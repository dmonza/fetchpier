// Generate three `.d.ts` files in `src/renderer/hooks/` from the hand-maintained
// source of truth at `packages/fetchpier-core/src/scripting/fp-api.d.ts`:
//
//   - `fp.base.d.ts.generated`          — shared interfaces (FpApi, FpRequest, …)
//   - `fp.preRequest.d.ts.generated`    — declares `fp: FpApiPreRequest`
//   - `fp.postResponse.d.ts.generated`  — declares `fp: FpApiPostResponse`
//
// The two phase files derive their shape from the base via `Omit` / `Readonly`
// so there is still a single source of truth. The editor mounts the base file
// plus one phase file per language-service instance (REQ-42).
//
// Modes:
//   - default: regenerate all three output files.
//   - --check: compare what would be emitted against the tracked files and
//     exit non-zero on drift (with a diff-friendly message).

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

export const SOURCE_PATH = resolve(ROOT, 'packages/fetchpier-core/src/scripting/fp-api.d.ts')

export const BASE_OUTPUT_PATH = resolve(ROOT, 'src/renderer/hooks/fp.base.d.ts.generated')
export const PRE_REQUEST_OUTPUT_PATH = resolve(
  ROOT,
  'src/renderer/hooks/fp.preRequest.d.ts.generated'
)
export const POST_RESPONSE_OUTPUT_PATH = resolve(
  ROOT,
  'src/renderer/hooks/fp.postResponse.d.ts.generated'
)

const BASE_HEADER = [
  '// AUTO-GENERATED by scripts/generate-fp-dts.mjs — DO NOT EDIT.',
  '// Source: src/main/scripting/fp-api.d.ts',
  '// Regenerate with: npm run generate:fp-dts',
  '//',
  '// Shared Fetchpier scripting type declarations mounted in the renderer TypeScript VFS.',
  '// Phase-specific files (fp.preRequest / fp.postResponse) derive from',
  '// these base interfaces to narrow `fp` per execution phase.',
  ''
].join('\n')

const PHASE_HEADER_TEMPLATE = (phase) =>
  [
    '// AUTO-GENERATED by scripts/generate-fp-dts.mjs — DO NOT EDIT.',
    '// Source: src/main/scripting/fp-api.d.ts',
    '// Regenerate with: npm run generate:fp-dts',
    '//',
    `// Phase-scoped Fetchpier types for ${phase} scripts. Paired with`,
    '// fp.base.d.ts.generated (both files are mounted in the VFS for the',
    '// matching LanguageService instance).',
    ''
  ].join('\n')

const PRE_REQUEST_BODY = [
  '/**',
  ' * Fetchpier API shape available inside **pre-request** scripts.',
  ' *',
  " * The HTTP fetch hasn't happened yet, so `response` is not available.",
  ' * `request` is mutable — assignments are persisted to the outgoing request.',
  ' */',
  "interface FpApiPreRequest extends Omit<FpApi, 'response'> {",
  '  /**',
  '   * ⚠️ `response` is **not available** in pre-request scripts — the HTTP',
  '   * request has not been sent yet. Access it from a post-response script',
  '   * instead.',
  '   */',
  '  readonly response: never',
  '}',
  '',
  '/** The Fetchpier global available in pre-request scripts. */',
  'declare const fp: FpApiPreRequest',
  ''
].join('\n')

const POST_RESPONSE_BODY = [
  '/**',
  ' * Fetchpier API shape available inside **post-response** scripts.',
  ' *',
  ' * The HTTP fetch already occurred, so `response` is always present and',
  ' * `request` is read-only (mutations would be silently ignored at runtime).',
  ' */',
  "interface FpApiPostResponse extends Omit<FpApi, 'request' | 'response'> {",
  '  /** The request that was sent. Read-only: the fetch already happened. */',
  '  readonly request: Readonly<FpRequest>',
  '  /** The HTTP response. Always defined in post-response scripts. */',
  '  readonly response: FpResponse',
  '}',
  '',
  '/** The Fetchpier global available in post-response scripts. */',
  'declare const fp: FpApiPostResponse',
  ''
].join('\n')

/**
 * Strip `import`/`export` declarations from a `.d.ts` source so its type
 * declarations become ambient in the consumer VFS. Returns the transformed
 * body (without header/footer).
 *
 * @param {string} source Contents of the source `.d.ts`.
 * @returns {string}
 */
export function transformSource(source) {
  const lines = source.split(/\r?\n/)
  /** @type {string[]} */
  const out = []
  let inMultilineImport = false

  for (const rawLine of lines) {
    const line = rawLine

    // Skip multi-line `import { … } from '…'` statements — rare in a .d.ts
    // source but supported for robustness.
    if (inMultilineImport) {
      if (/from\s+['"][^'"]+['"]\s*;?\s*$/.test(line)) inMultilineImport = false
      continue
    }

    // Single-line imports: `import type { … } from '…'` or `import { … } from '…'`
    if (/^\s*import\s/.test(line)) {
      if (/from\s+['"][^'"]+['"]\s*;?\s*$/.test(line)) continue
      inMultilineImport = true
      continue
    }

    // `export type { … }` re-exports are stripped entirely (declarations
    // already exist locally as the source-of-truth interfaces/types).
    if (/^\s*export\s+type\s*\{[^}]*\}/.test(line)) continue

    // Strip the leading `export` keyword from declarations.
    // Handles: `export interface`, `export type`, `export declare`, etc.
    const stripped = line.replace(/^(\s*)export\s+/, '$1')
    out.push(stripped)
  }

  // Trim trailing blank lines so the footer lands clean.
  while (out.length > 0 && out[out.length - 1].trim() === '') out.pop()
  return out.join('\n')
}

/**
 * Build the base `.d.ts` string (shared interfaces) from the source.
 *
 * @param {string} source
 * @returns {string}
 */
export function buildBase(source) {
  return BASE_HEADER + '\n' + transformSource(source) + '\n'
}

/**
 * Build the pre-request phase `.d.ts` string. Self-contained: does not
 * reference the base file via `///reference` — instead both files are added
 * to the VFS root files list so the base declarations are in scope.
 *
 * @returns {string}
 */
export function buildPreRequest() {
  return PHASE_HEADER_TEMPLATE('pre-request') + '\n' + PRE_REQUEST_BODY
}

/**
 * Build the post-response phase `.d.ts` string.
 *
 * @returns {string}
 */
export function buildPostResponse() {
  return PHASE_HEADER_TEMPLATE('post-response') + '\n' + POST_RESPONSE_BODY
}

function allOutputs(source) {
  return [
    { path: BASE_OUTPUT_PATH, content: buildBase(source) },
    { path: PRE_REQUEST_OUTPUT_PATH, content: buildPreRequest() },
    { path: POST_RESPONSE_OUTPUT_PATH, content: buildPostResponse() }
  ]
}

function main() {
  const args = process.argv.slice(2)
  const isCheck = args.includes('--check')

  if (!existsSync(SOURCE_PATH)) {
    console.error(`Source not found: ${SOURCE_PATH}`)
    process.exit(2)
  }
  const source = readFileSync(SOURCE_PATH, 'utf8')
  const outputs = allOutputs(source)

  if (isCheck) {
    let drift = false
    for (const { path, content } of outputs) {
      if (!existsSync(path)) {
        console.error(
          `Tracked output is missing: ${path}\n` +
            `Run \`npm run generate:fp-dts\` and commit the result.`
        )
        drift = true
        continue
      }
      const tracked = readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
      const candidate = content.replace(/\r\n/g, '\n')
      if (tracked !== candidate) {
        console.error(
          `${path} is out of sync with fp-api.d.ts.\n` + `Regenerate with: npm run generate:fp-dts`
        )
        drift = true
      }
    }
    if (drift) process.exit(1)
    console.log('Fetchpier .d.ts generated files are up to date.')
    return
  }

  for (const { path, content } of outputs) {
    writeFileSync(path, content, 'utf8')
    console.log(`Wrote ${path}`)
  }
}

const isMainModule =
  import.meta.url === `file://${process.argv[1]}` ||
  import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}`

if (isMainModule) {
  main()
}
